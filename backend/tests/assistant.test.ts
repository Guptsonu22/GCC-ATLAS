import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { getDatabase, initializeSchema, closeDatabase } from '../src/db/database';
import { seedDatabase } from '../src/db/seed';
import { createAssistantService } from '../src/services/assistant';
import type { Database } from 'sqlite';

let db: Database;

beforeAll(async () => {
  delete process.env.AI_API_KEY; // force deterministic demo mode
  db = await getDatabase();
  await initializeSchema(db);
  await seedDatabase(db, { reset: true });
});

describe('assistant (deterministic demo mode)', () => {
  it('answers city comparison queries with a comparison table and citations', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'Compare Bengaluru and Hyderabad for GCC location decision' });

    expect(response.is_demo_mode).toBe(true);
    expect(response.insufficient_evidence).toBe(false);
    expect(response.answer).toMatch(/Comparison: Bengaluru vs Hyderabad/i);
    expect(response.answer).toMatch(/estimate/i);
    expect(response.citations.length).toBeGreaterThan(0);
    for (const citation of response.citations) {
      expect(citation.url).toMatch(/^https?:\/\//);
      expect(citation.title).toBeTruthy();
    }
  });

  it('answers single-city queries with tracked counts', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'Tell me about Chennai GCC talent availability' });
    expect(response.answer).toMatch(/Chennai/g);
    expect(response.insufficient_evidence).toBe(false);
  });

  it('answers company queries with sector and status', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'Tell me about Microsoft India operations' });
    expect(response.answer).toMatch(/Microsoft India/i);
    expect(response.answer).toMatch(/operating_status|active|expanding/i);
  });

  it('answers policy queries with verification caveat', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'What is the Karnataka GCC policy?' });
    expect(response.answer).toMatch(/Karnataka GCC Policy/i);
    expect(response.answer).toMatch(/verify/i);
  });

  it('states insufficient evidence for unknown topics', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'What is the quarterly revenue of widget manufacturing in Peru?' });
    expect(response.insufficient_evidence).toBe(true);
    expect(response.confidence).toBe('low');
    expect(response.answer).toMatch(/sufficient evidence/i);
    expect(response.is_demo_mode).toBe(true);
  });

  it('never claims to be an LLM in demo mode', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'Compare Pune and Mumbai' });
    expect(response.is_demo_mode).toBe(true);
    expect(response.answer).toMatch(/not generated by an LLM/i);
  });

  it('handles policy + city queries', async () => {
    const service = createAssistantService(db);
    const response = await service.answer({ query: 'Which states have GCC policies and how do Tamil Nadu incentives compare?' });
    expect(response.answer).toMatch(/Karnataka GCC Policy|Tamil Nadu GCC Policy/i);
  });
});

afterAll(async () => {
  await closeDatabase();
});